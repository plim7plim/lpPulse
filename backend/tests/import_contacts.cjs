const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = { window: {}, document: { getElementById: () => null } };
vm.runInNewContext(fs.readFileSync('js/importar-contatos.js','utf8'),context);
const { normalize, collect } = context.window.PulseContacts;
assert.equal(normalize('(62) 99840-6502'),'+5562998406502');
assert.equal(normalize('+55 62 99840 6502'),'+5562998406502');
assert.equal(normalize(5562998406502),'+5562998406502');
assert.equal(normalize('62998406502'),'+5562998406502');
for (const value of ['123','1.23E+10','telefone','=123',Infinity,123.4]) assert.equal(normalize(value),null);
const data = collect([['Nome','Telefone'],['A','62998406502'],['B','+55 62 99840-6502'],['C','123'],['D','']],1,true);
assert.equal(data.numbers.length,1); assert.equal(data.duplicates,1); assert.equal(data.invalid.length,1); assert.equal(data.invalid[0].line,4);
const XLSX = require('../../js/vendor/xlsx.full.min.js');
const sheet = XLSX.utils.aoa_to_sheet([['Nome','Telefone'],['A',62998406502],['B','+5562998406502']]);
const book = XLSX.utils.book_new(); XLSX.utils.book_append_sheet(book,sheet,'Contatos');
const loaded = XLSX.read(XLSX.write(book,{type:'buffer',bookType:'xlsx'}),{type:'buffer',sheetRows:10002});
assert.equal(collect(XLSX.utils.sheet_to_json(loaded.Sheets.Contatos,{header:1,raw:true}),1,true).numbers.length,1);
const csv = XLSX.read('Nome;Telefone\nA;62998406502\nB;+5562998406502',{type:'string',raw:true});
assert.equal(collect(XLSX.utils.sheet_to_json(csv.Sheets[csv.SheetNames[0]],{header:1,raw:true}),1,true).duplicates,1);
console.log('Contacts: normalization, deduplication, invalid rows, XLSX and CSV checks passed.');
